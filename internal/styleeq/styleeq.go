// Package styleeq writes core/style_equal_gen.go: core.Style's Equal method,
// one comparison per field, generated from the struct's own declaration.
//
// # Why a generated method and not reflect.DeepEqual
//
// reconcile compares every node's Style on every pass, and a Style has about
// seventy fields. reflect.DeepEqual walks them through reflection, which was
// most of the diff's cost: 975 µs at 1,001 nodes against 97 µs for a
// field-by-field comparison (N-138, plan P2). A hand-written method would be
// as fast, and would fall out of date the first time someone added a field
// and forgot it, which would make the diff skip a change silently. So the
// method is generated, and this package's test fails when the committed file
// is not what the generator writes from the current struct, the way
// internal/apidoc keeps docs/api honest.
//
// # How each field is compared
//
//	pointer-free comparable  (string, bool, numbers, a struct of those,
//	                          a named type over any of them)    a.F == b.F
//	*Style                   (HoverStyle, FocusStyle)           a.F.Equal(b.F)
//	map[string]Style         (PseudoStates)                     equalStyleMap
//	anything else                                               reflect.DeepEqual
//
// The last row is the safety net: a field of a kind this generator does not
// know (a slice, an interface, a pointer to something else) is still compared
// correctly, only slowly, rather than by == on a pointer, which would compare
// identity where the diff needs content.
//
// The semantics match reflect.DeepEqual's on every Style, which the test
// fuzzes: floats by == (so a NaN never equals itself and -0 equals 0), nil and
// empty maps unequal, a nil and a non-nil pointer unequal.
//
// # Why it reads source rather than reflecting over core.Style
//
// A generator that imports core compiles core, including the generated file it
// is about to replace. Remove a field and that file no longer compiles, so the
// generator could not run to fix it. Parsing core's source (skipping the
// generated file) has no such loop.
package styleeq

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// GeneratedFile is the file Generate's output belongs in, relative to core's
// directory.
const GeneratedFile = "style_equal_gen.go"

// Generate returns the contents of core/style_equal_gen.go, read from the
// package in coreDir.
func Generate(coreDir string) ([]byte, error) {
	types, err := typeDecls(coreDir)
	if err != nil {
		return nil, err
	}
	style, ok := types["Style"].(*ast.StructType)
	if !ok {
		return nil, fmt.Errorf("styleeq: no struct type Style in %s", coreDir)
	}

	var (
		terms      []string
		needsDeep  bool
		needsMap   bool
		fieldCount int
	)
	for _, f := range style.Fields.List {
		for _, name := range f.Names {
			fieldCount++
			n := name.Name
			switch {
			case isPtrToStyle(f.Type):
				terms = append(terms, fmt.Sprintf("s.%s.Equal(o.%s)", n, n))
			case isStyleMap(f.Type):
				needsMap = true
				terms = append(terms, fmt.Sprintf("equalStyleMap(s.%s, o.%s)", n, n))
			case pointerFree(f.Type, types, map[string]bool{}):
				terms = append(terms, fmt.Sprintf("s.%s == o.%s", n, n))
			default:
				needsDeep = true
				terms = append(terms, fmt.Sprintf("reflect.DeepEqual(s.%s, o.%s)", n, n))
			}
		}
		if len(f.Names) == 0 {
			return nil, fmt.Errorf("styleeq: Style has an embedded field, which this generator does not handle")
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/styleeq/gen; DO NOT EDIT.\n\n")
	b.WriteString("package core\n\n")
	if needsDeep {
		b.WriteString("import \"reflect\"\n\n")
	}
	fmt.Fprintf(&b, `// Equal reports whether s and o hold the same style, field by field: what
// reflect.DeepEqual would say, without the reflection. reconcile asks it of
// every node on every pass. Either side may be nil; two nils are equal.
//
// Generated from the struct's %d fields by internal/styleeq, whose test fails
// when a field is added and this file is not regenerated.
func (s *Style) Equal(o *Style) bool {
	if s == o {
		return true
	}
	if s == nil || o == nil {
		return false
	}
	return %s
}
`, fieldCount, strings.Join(terms, " &&\n\t\t"))
	if needsMap {
		b.WriteString(`
// equalStyleMap is reflect.DeepEqual for a map of Styles: a nil map and an
// empty one differ, as they do there (and on the wire, where omitzero drops
// only the nil one).
func equalStyleMap(a, b map[string]Style) bool {
	if (a == nil) != (b == nil) || len(a) != len(b) {
		return false
	}
	for k, av := range a {
		bv, ok := b[k]
		if !ok || !av.Equal(&bv) {
			return false
		}
	}
	return true
}
`)
	}
	return format.Source(b.Bytes())
}

// typeDecls parses every non-test Go file of the package in dir, except the
// generated file, and returns its named types by name.
func typeDecls(dir string) (map[string]ast.Expr, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	out := map[string]ast.Expr{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == GeneratedFile {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.TYPE {
				continue
			}
			for _, sp := range g.Specs {
				ts := sp.(*ast.TypeSpec)
				out[ts.Name.Name] = ts.Type
			}
		}
	}
	return out, nil
}

func isPtrToStyle(e ast.Expr) bool {
	st, ok := e.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := st.X.(*ast.Ident)
	return ok && id.Name == "Style"
}

func isStyleMap(e ast.Expr) bool {
	m, ok := e.(*ast.MapType)
	if !ok {
		return false
	}
	k, kok := m.Key.(*ast.Ident)
	v, vok := m.Value.(*ast.Ident)
	return kok && vok && k.Name == "string" && v.Name == "Style"
}

// basicKinds are the predeclared types == compares by value.
var basicKinds = map[string]bool{
	"string": true, "bool": true, "byte": true, "rune": true,
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true, "uintptr": true,
	"float32": true, "float64": true, "complex64": true, "complex128": true,
}

// pointerFree reports whether == on a value of type e compares its whole
// content: a basic type, a named type declared in core over one, or a struct
// or array of such. Anything that holds a pointer, map, slice, interface,
// func or channel, or names a type from another package, is not, since there
// == compares identity or does not compile. seen guards a recursive type,
// which cannot be pointer-free anyway.
func pointerFree(e ast.Expr, types map[string]ast.Expr, seen map[string]bool) bool {
	switch t := e.(type) {
	case *ast.Ident:
		if basicKinds[t.Name] {
			return true
		}
		decl, ok := types[t.Name]
		if !ok || seen[t.Name] {
			return false
		}
		seen[t.Name] = true
		return pointerFree(decl, types, seen)
	case *ast.ParenExpr:
		return pointerFree(t.X, types, seen)
	case *ast.ArrayType:
		return t.Len != nil && pointerFree(t.Elt, types, seen) // an array, not a slice
	case *ast.StructType:
		for _, f := range t.Fields.List {
			if !pointerFree(f.Type, types, seen) {
				return false
			}
		}
		return true
	}
	return false
}
